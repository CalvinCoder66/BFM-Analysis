"""Writing the roster: `data/roster.json` for later stages and `data/ROSTER.md` for people."""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING

from .roster import Roster

if TYPE_CHECKING:
    from .extract import Extraction

NATIONS = {
    'usa': 'USA',
    'germany': 'Germany',
    'ussr': 'USSR',
    'britain': 'Britain',
    'japan': 'Japan',
    'china': 'China',
    'italy': 'Italy',
    'france': 'France',
    'sweden': 'Sweden',
    'israel': 'Israel',
}


def _br(low: float, high: float) -> str:
    return f'{low:.1f}' if low == high else f'{low:.1f}–{high:.1f}'


def render_markdown(roster: Roster) -> str:
    p = roster.provenance
    r = roster.rules
    units = sum(len(e.variants) for e in roster.entries)
    lines = [
        '# Aircraft roster',
        '',
        '<!-- Generated by `mise run data:roster`. Do not edit by hand. -->',
        '',
        f'War Thunder **{p.game_version}** (datamine ref `{p.ref}`, commit `{p.commit[:12]}`). '
        f'Realistic Battles BR {r.br_min:.1f}–{r.br_max:.1f}, classes '
        f'{", ".join(f"`{c}`" for c in r.unit_classes)}.',
        '',
        f'**{len(roster.entries)} aircraft** with a unique flight model, covering {units} '
        f'in-game units. {len(roster.excluded)} units in the BR range are excluded (listed below).',
        '',
        '| BR | Aircraft | Nations | Merged variants | Flight model |',
        '| --- | --- | --- | --- | --- |',
    ]
    for e in roster.entries:
        nations = sorted({NATIONS.get(v.nation, v.nation) for v in e.variants})
        others = [
            f'{v.name} ({NATIONS.get(v.nation, v.nation)}, {v.br:.1f})' for v in e.variants[1:]
        ]
        lines.append(
            f'| {_br(*e.br_range)} | {e.name} | {", ".join(nations)} | '
            f'{"; ".join(others) or "—"} | `{e.fm_file}` |'
        )
    lines += ['', '## Excluded', '', '| BR | Unit | Reason |', '| --- | --- | --- |']
    for x in sorted(roster.excluded, key=lambda x: (x.br, x.unit_id)):
        lines.append(f'| {x.br:.1f} | {x.name} (`{x.unit_id}`) | {x.reason} |')
    return '\n'.join(lines) + '\n'


def write_roster(roster: Roster, out_dir: Path) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    json_path = out_dir / 'roster.json'
    md_path = out_dir / 'ROSTER.md'
    json_path.write_text(roster.model_dump_json(indent=2) + '\n', encoding='utf-8', newline='\n')
    md_path.write_text(render_markdown(roster), encoding='utf-8', newline='\n')
    return json_path, md_path


G0 = 9.80665
#: Limiter strength from which the game's pitch limiter is treated as a hard G limit.
HARD_LIMIT_STRENGTH = 0.99


def render_extraction_markdown(extraction: Extraction) -> str:
    p = extraction.provenance
    lines = [
        '# Extracted aircraft data (milestone 2: basic fields)',
        '',
        '<!-- Generated by `mise run data:extract`. Do not edit by hand. -->',
        '',
        f'War Thunder **{p.game_version}** (datamine ref `{p.ref}`, commit `{p.commit[:12]}`). '
        f'{len(extraction.aircraft)} aircraft extracted, {len(extraction.failures)} failed.',
        '',
        'Columns marked † rest on interpretations that the in-game validation flights must '
        'confirm:',
        '',
        '- **Wing-break G** assumes `CritOverload` is per wing (so the total is twice the stored '
        'value), at 50% internal fuel without ammunition or stores.',
        '- **Instructor** shows the steady and brief-peak fractions read from `overloadMult`, and '
        'the G they give if they apply to the wing-break load. Values above 1.0 suggest they apply '
        'to something else, which test card D will settle. "?" means the files give no value.',
        '- **Pitch limiter** is the game\'s `Autopilot.Pitch` load-factor limit: "hard" when its '
        'strength is ≥ 0.99, otherwise "soft" with the strength in brackets.',
        '',
        '| BR | Aircraft | Format | Wing area (m²) | Span (m) | Empty (kg) | Fuel (kg) '
        '| Wing-break G † | Instructor † | Pitch limiter † | VNE (km/h) | MNE |',
        '| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | --- | --- | ---: | ---: |',
    ]
    for a in extraction.aircraft:
        b = a.basic
        mass = b.empty_mass_kg.value + 0.5 * b.internal_fuel_kg.value
        wing_break_g = b.wing_break_load_N.value / (mass * G0)
        i = b.instructor.value
        if i.steady_fraction is None or i.peak_fraction is None:
            instructor = '?'
        else:
            instructor = (
                f'{i.steady_fraction:.2f} / {i.peak_fraction:.2f} '
                f'({i.steady_fraction * wing_break_g:.1f} / {i.peak_fraction * wing_break_g:.1f} g)'
            )
        fc = b.flight_control.value
        if fc.max_g is None:
            limiter = 'none'
        elif (fc.limiter_strength or 0) >= HARD_LIMIT_STRENGTH:
            limiter = f'hard {fc.max_g:.0f} g'
        else:
            limiter = f'soft {fc.max_g:.0f} g ({fc.limiter_strength})'
        low, high = a.entry.br_range
        br = f'{low:.1f}' if low == high else f'{low:.1f}–{high:.1f}'
        lines.append(
            f'| {br} | {a.entry.name} | {b.fm_format.replace("_", " ")} '
            f'| {b.wing_area_m2.value:.1f} | {b.wing_span_m.value:.2f} '
            f'| {b.empty_mass_kg.value:,.0f} | {b.internal_fuel_kg.value:,.0f} '
            f'| {wing_break_g:.1f} | {instructor} | {limiter} '
            f'| {b.vne_kmh.value:,.0f} | {b.mne.value:.2f} |'
        )
    if extraction.failures:
        lines += ['', '## Failed', '', '| Entry | Error |', '| --- | --- |']
        lines += [f'| `{f.entry_id}` | {f.error} |' for f in extraction.failures]
    return '\n'.join(lines) + '\n'


def write_extraction(extraction: Extraction, report_dir: Path, scratch_dir: Path) -> Path:
    report_dir.mkdir(parents=True, exist_ok=True)
    scratch_dir.mkdir(parents=True, exist_ok=True)
    (scratch_dir / 'extraction.json').write_text(
        extraction.model_dump_json(indent=2) + '\n', encoding='utf-8', newline='\n'
    )
    report = report_dir / 'EXTRACTION.md'
    report.write_text(render_extraction_markdown(extraction), encoding='utf-8', newline='\n')
    return report
